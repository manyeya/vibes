/**
 * Types of tasks for categorization and filtering.
 */
export enum TaskType {
    /** User request tasks generated by PlanningPlugin */
    UserRequest = 'user_request',
    /** Subtasks created by the agent during task execution */
    SubTask = 'subtask',
    /** Error analysis tasks (e.g. from an error-handling flow) */
    ErrorAnalysis = 'error_analysis',
    /** Delegation tasks from SubAgentPlugin */
    Delegation = 'delegation',
    /** Background async work */
    Background = 'background',
}

/**
 * Task event types for the event listener system.
 */
export type TaskEventType = 'created' | 'updated' | 'completed' | 'failed';

/**
 * Task event listener callback type.
 */
export type TaskEventListener = (task: TaskItem) => void | Promise<void>;

