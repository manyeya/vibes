/**
 * Configuration for initializing a AgentHarness instance.
 */
export interface AgentHarnessConfig {
    /** The AI model to use */
    model: LanguageModel;
    /** The base system instructions */
    instructions: string;
    /** Optional display name for the agent (used in notifications) */
    name?: string;
    /** Custom instructions to extend the base system prompt */
    systemPrompt?: string;
    /** Additional custom tools available to the agent */
    tools?: Record<string, Tool<any, any>>;
    /** Maximum number of reasoning steps per invocation (default: 20) */
    maxSteps?: number;
    /** Optional custom stop condition(s) for the tool loop */
    stopWhen?: StopCondition<ToolSet> | Array<StopCondition<ToolSet>>;
    /** Maximum messages before context compression kicks in (default: 30) */
    maxContextMessages?: number;
    /** Model context window in tokens. Drives token-based compression. (default: 128000) */
    contextWindow?: number;
    /** Fraction of the context window at which compression kicks in, 0–1 (default: 0.7) */
    contextCompressionRatio?: number;
    /**
     * Minimum character length a single tool/assistant payload must reach
     * before restorable in-place compression will shrink it (default: 3000).
     * Raise it to let larger reads survive verbatim.
     */
    compressionThreshold?: number;
    /**
     * Fraction of the context window (0–1) the WHOLE conversation must reach
     * before per-message restorable compression runs at all (default: 0.7).
     * Below this, large reads are kept intact even if individually over
     * `compressionThreshold` — no gutting a big file read in an otherwise-empty
     * context. Set 0 to compress eagerly (legacy behaviour).
     */
    compressionGateRatio?: number;
    /**
     * Whether this agent emits the live context-usage gauge (default: true).
     * Set false for sub-agents so their (smaller) context doesn't clobber the
     * main conversation's gauge in the UI.
     */
    emitContextGauge?: boolean;
    /** Model temperature for controlling randomness */
    temperature?: number;
    /** Maximum retries for a single failing tool call (default: 2) */
    maxRetries?: number;
    /**
     * Tool-retry policy. `maxTotalRetries` caps retries across the WHOLE run
     * (default 20), so a transiently-failing tool can't keep retrying on every
     * call. Only transient errors (network / rate-limit / timeout / 5xx) are
     * retried at all; deterministic failures fail fast.
     */
    toolRetry?: { maxTotalRetries?: number };
    /** Callback for step progress updates (matches AI SDK's StepResult) */
    onStepFinish?: (stepResult: StepResult<ToolSet>) => void | Promise<void>;
    /** Custom plugins to extend agent behavior */
    plugins?: Plugin[];
    /** Enable telemetry for observability (default: false) */
    enableTelemetry?: boolean;
    /** The base directory for filesystem operations (e.g., 'workspace') */
    workspaceDir?: string;
    /**
     * Per-session plugin-state directory (plan.md, tasks.json, scratchpad.md,
     * tracked_files.json). Defaults to `workspaceDir`. For a workspace session
     * the sandbox root (`workspaceDir`) is the SHARED project dir, while this
     * points at `{projectDir}/.vibes/sessions/{sessionId}/` so per-session state
     * stays isolated.
     */
    stateDir?: string;
    /**
     * Cross-session shared-state directory (memories.json, workflows.json).
     * Defaults to a value derived from `workspaceDir`. Set explicitly so that
     * an opened external repo never receives global vibes state.
     */
    sharedDir?: string;
    /** List of tool names that require explicit user approval before execution */
    toolsRequiringApproval?: ToolsRequiringApprovalConfig;
    /** Optional whitelist of tool names allowed for this agent instance */
    allowedTools?: string[];
    /** Optional blacklist of tool names to block (takes precedence over allowedTools) */
    blockedTools?: string[];
    /**
     * Per-run budgets (token / cost / tool-call caps). Enforced as native
     * `stopWhen` conditions — the loop halts once a cap is reached.
     */
    budgets?: BudgetConfig;
    /**
     * Stuck-loop detection: halt the run when the agent repeats the same tool
     * call (same name + input) too many times in a short window. Enforced as a
     * native `stopWhen` condition, like {@link budgets}.
     */
    loopDetection?: LoopDetectionConfig;
    /**
     * Adaptive reasoning effort: pick a model reasoning-effort tier from the
     * request's apparent complexity and pass it via provider-namespaced
     * `providerOptions`. `true` enables it with defaults; an object enables it
     * with options; omit/false to disable. No-op on models without reasoning.
     */
    adaptiveReasoning?: boolean | AdaptiveReasoningConfig;
    /**
     * Redact known secrets (API keys, tokens, env assignments) from tool
     * results before they reach the model context or the stream (default true).
     * Set false in a fully trusted environment.
     */
    redactToolIO?: boolean;
}

